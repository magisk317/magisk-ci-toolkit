#!/usr/bin/env bash
set -euo pipefail

root_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
generator="$root_dir/codegen/sync_consumer_bootstrap.sh"
test_ref=0123456789abcdef0123456789abcdef01234567
tmp_dir="$(mktemp -d)"
trap 'rm -rf "$tmp_dir"' EXIT

bash "$generator" "$tmp_dir" "$test_ref"
bash -n "$tmp_dir/scripts/resolve_ci_toolkit.sh" "$tmp_dir/scripts/sync_shared_gradle.sh"
grep -Fq "TOOLKIT_REF=\"\${MAGISK_CI_TOOLKIT_REF:-$test_ref}\"" \
  "$tmp_dir/scripts/resolve_ci_toolkit.sh"
grep -Fq 'TOOLKIT_REPOSITORY_AUTH=' \
  "$tmp_dir/scripts/resolve_ci_toolkit.sh"
grep -Fq 'git -C "$TOOLKIT_DIR" fetch --depth 1 origin "$TOOLKIT_REF"' \
  "$tmp_dir/scripts/resolve_ci_toolkit.sh"
grep -Fq 'Generated by magisk-ci-toolkit/codegen/sync_consumer_bootstrap.sh' \
  "$tmp_dir/scripts/sync_shared_gradle.sh"
bash "$generator" --check "$tmp_dir" "$test_ref"

printf '\n# drift\n' >> "$tmp_dir/scripts/resolve_ci_toolkit.sh"
if bash "$generator" --check "$tmp_dir" "$test_ref" >/dev/null 2>&1; then
  echo "drift check accepted a modified resolver" >&2
  exit 1
fi

if bash "$generator" "$tmp_dir" main >/dev/null 2>&1; then
  echo "generator accepted a moving toolkit ref" >&2
  exit 1
fi

echo "consumer bootstrap tests passed"
