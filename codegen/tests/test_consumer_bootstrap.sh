#!/usr/bin/env bash
set -euo pipefail

root_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
generator="$root_dir/codegen/sync_consumer_bootstrap.sh"
test_ref=0123456789abcdef0123456789abcdef01234567
tmp_dir="$(mktemp -d)"
trap 'rm -rf "$tmp_dir"' EXIT

bash "$generator" "$tmp_dir" "$test_ref"
bash -n "$tmp_dir/scripts/resolve_ci_toolkit.sh" "$tmp_dir/scripts/sync_shared_gradle.sh"
grep -Fq "TOOLKIT_REF=\"\${MAGISK_CI_TOOLKIT_REF:-$test_ref}\"" \
  "$tmp_dir/scripts/resolve_ci_toolkit.sh"
grep -Fq 'TOOLKIT_REPOSITORY_AUTH=' \
  "$tmp_dir/scripts/resolve_ci_toolkit.sh"
# The toolkit repository is private: the generated resolver must inject the CI
# job token, keep the canonical magisk3171/shared/ path, and derive TOOLKIT_DIR
# from the script location rather than $PWD. A resolver missing these fails the
# MR-only jobs with "could not read Username for 'https://gitlab.com'".
grep -Fq 'gitlab-ci-token:${CI_JOB_TOKEN}@' \
  "$tmp_dir/scripts/resolve_ci_toolkit.sh"
grep -Fq 'magisk3171/shared/magisk-ci-toolkit.git' \
  "$tmp_dir/scripts/resolve_ci_toolkit.sh"
grep -Fq 'ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"' \
  "$tmp_dir/scripts/resolve_ci_toolkit.sh"
# Four remote commands carry the authenticated URL, not three: the
# snapshot-recovery rebuild initialises a fresh store and has to add the remote
# with credentials again before it can fetch main.
if [ "$(grep -c 'origin "\$TOOLKIT_REPOSITORY_AUTH"' "$tmp_dir/scripts/resolve_ci_toolkit.sh")" -ne 4 ]; then
  echo "generated resolver must route all four remote commands through TOOLKIT_REPOSITORY_AUTH" >&2
  exit 1
fi
grep -Fq 'git -C "$TOOLKIT_DIR" fetch --depth 1 origin "$TOOLKIT_REF"' \
  "$tmp_dir/scripts/resolve_ci_toolkit.sh"
grep -Fq 'Generated by magisk-ci-toolkit/codegen/sync_consumer_bootstrap.sh' \
  "$tmp_dir/scripts/sync_shared_gradle.sh"

# --- behaviour, against a local file:// repository so the contract is testable
# without a GitLab credential. MAGISK_CI_TOOLKIT_REPOSITORY / _DIR / _REF are the
# resolver's own overrides, so the generated script runs unmodified either way.
toolkit_repo="$tmp_dir/toolkit_src"
git -c init.defaultBranch=main init --quiet "$toolkit_repo"
git -C "$toolkit_repo" -c user.email=ci@test -c user.name=ci commit --quiet --allow-empty -m first
commit_a="$(git -C "$toolkit_repo" rev-parse HEAD)"
git -C "$toolkit_repo" -c user.email=ci@test -c user.name=ci commit --quiet --allow-empty -m second
commit_b="$(git -C "$toolkit_repo" rev-parse HEAD)"

resolved_dir="$(MAGISK_CI_TOOLKIT_REPOSITORY="file://$toolkit_repo" \
  MAGISK_CI_TOOLKIT_DIR="$tmp_dir/store_ok" \
  MAGISK_CI_TOOLKIT_REF="$commit_b" \
  bash "$tmp_dir/scripts/resolve_ci_toolkit.sh" 2>/dev/null)"
if [[ "$resolved_dir" != "$tmp_dir/store_ok" ]]; then
  echo "resolver must print the toolkit dir it resolved" >&2
  exit 1
fi
if [[ "$(git -C "$tmp_dir/store_ok" rev-parse HEAD)" != "$commit_b" ]]; then
  echo "resolver must land exactly on the pinned ref" >&2
  exit 1
fi

# A store that already holds another commit must still be re-resolved to the pin.
# This is the shape the recovery ladder exists for: successive jobs leave
# depth-1 fragments of different commits behind, and the resolver must end on the
# pinned ref no matter what the store currently believes.
MAGISK_CI_TOOLKIT_REPOSITORY="file://$toolkit_repo" \
  MAGISK_CI_TOOLKIT_DIR="$tmp_dir/store_ok" \
  MAGISK_CI_TOOLKIT_REF="$commit_a" \
  bash "$tmp_dir/scripts/resolve_ci_toolkit.sh" >/dev/null 2>&1
MAGISK_CI_TOOLKIT_REPOSITORY="file://$toolkit_repo" \
  MAGISK_CI_TOOLKIT_DIR="$tmp_dir/store_ok" \
  MAGISK_CI_TOOLKIT_REF="$commit_b" \
  bash "$tmp_dir/scripts/resolve_ci_toolkit.sh" >/dev/null 2>&1
if [[ "$(git -C "$tmp_dir/store_ok" rev-parse HEAD)" != "$commit_b" ]]; then
  echo "resolver left the store on $commit_a instead of re-resolving to the pin" >&2
  exit 1
fi

# A pinned ref that is not on main at all (a mistyped SHA, a branch rewritten
# away) must fail loudly, and the failure must happen before any checkout: a
# resolver that quietly lands on main would run the whole pipeline against a
# toolkit the pin never named.
bogus_ref="$(printf '%040d' 0)"
err_file="$tmp_dir/bogus.err"
if MAGISK_CI_TOOLKIT_REPOSITORY="file://$toolkit_repo" \
   MAGISK_CI_TOOLKIT_DIR="$tmp_dir/store_bogus" \
   MAGISK_CI_TOOLKIT_REF="$bogus_ref" \
   bash "$tmp_dir/scripts/resolve_ci_toolkit.sh" >/dev/null 2>"$err_file"; then
  echo "resolver accepted a pinned ref that is not on main" >&2
  exit 1
fi
grep -q "is not on main" "$err_file" || {
  echo "resolver must name the containment failure, got:" >&2
  cat "$err_file" >&2
  exit 1
}
if git -C "$tmp_dir/store_bogus" rev-parse HEAD >/dev/null 2>&1; then
  echo "resolver checked out a store after failing the pin (silent fallback to main)" >&2
  exit 1
fi

# The recovery ladder, asserted structurally: exact-ref fetch, containment proved
# before every checkout, and a rebuild path. The incoherent-shallow-store case
# that motivated the ladder cannot be forced deterministically offline, so only
# its shape is checked here; the two behaviours above are its real guarantees.
grep -Fq 'fetch --depth 1 origin "$TOOLKIT_REF"' "$tmp_dir/scripts/resolve_ci_toolkit.sh"
grep -Fq 'merge-base --is-ancestor "$TOOLKIT_REF" FETCH_HEAD' "$tmp_dir/scripts/resolve_ci_toolkit.sh"
grep -Fq 'WARN: toolkit snapshot incoherent, rebuilding from scratch' "$tmp_dir/scripts/resolve_ci_toolkit.sh"
if grep -Fq 'checkout --detach --force FETCH_HEAD' "$tmp_dir/scripts/resolve_ci_toolkit.sh"; then
  echo "resolver must check out the pinned ref, never FETCH_HEAD of a branch fetch" >&2
  exit 1
fi

bash "$generator" --check "$tmp_dir" "$test_ref"

printf '\n# drift\n' >> "$tmp_dir/scripts/resolve_ci_toolkit.sh"
if bash "$generator" --check "$tmp_dir" "$test_ref" >/dev/null 2>&1; then
  echo "drift check accepted a modified resolver" >&2
  exit 1
fi

if bash "$generator" "$tmp_dir" main >/dev/null 2>&1; then
  echo "generator accepted a moving toolkit ref" >&2
  exit 1
fi

echo "consumer bootstrap tests passed"
